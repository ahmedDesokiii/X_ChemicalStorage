<#
  الخطوة 2 — ضبط Mosquitto (الـ MQTT broker اللي البوابات بتبعتله)
  - بيفتح البورت 1883 على شبكة المعمل بس (البوابات تقدر توصل، والنت لأ)

  الطريقة البسيطة (شبكة مقفولة للفريزرات بس) — من غير باسورد:
      .\2-configure-mosquitto.ps1
  لو عايزة باسورد (نفس اليوزر والباسورد يتحطوا في البوابات وفي صفحة Settings):
      .\2-configure-mosquitto.ps1 -User biobank -Password 'Strong#Pass1'
#>
param(
    [string]$User = '',
    [string]$Password = '',
    [string]$MosquittoDir = 'C:\Program Files\mosquitto'
)
$ErrorActionPreference = 'Stop'
if (-not (Test-Path "$MosquittoDir\mosquitto.exe")) { throw "Mosquitto مش موجود في $MosquittoDir" }

$conf = Join-Path $MosquittoDir 'mosquitto.conf'
$pwFile = Join-Path $MosquittoDir 'passwd'
$logDir = 'C:\ProgramData\mosquitto'
New-Item -ItemType Directory -Path $logDir -Force | Out-Null

if (Test-Path $conf) { Copy-Item $conf "$conf.bak-$(Get-Date -Format yyyyMMddHHmm)" }
$useAuth = [bool]$User
if ($useAuth -and -not $Password) { throw 'لو حددتي -User لازم -Password كمان' }
$authLines = if ($useAuth) { "allow_anonymous false`npassword_file $pwFile" } else { 'allow_anonymous true' }
@"
# BioBank — generated by 2-configure-mosquitto.ps1
listener 1883 0.0.0.0
$authLines
persistence true
persistence_location $logDir\
log_dest file $logDir\mosquitto.log
log_type error
log_type warning
log_type notice
"@ | Set-Content -Path $conf -Encoding ascii

if ($useAuth) {
    & "$MosquittoDir\mosquitto_passwd.exe" -c -b $pwFile $User $Password
    if ($LASTEXITCODE -ne 0) { throw 'فشل إنشاء ملف الباسورد' }
}

if (-not (Get-NetFirewallRule -DisplayName 'BioBank MQTT 1883' -ErrorAction SilentlyContinue)) {
    New-NetFirewallRule -DisplayName 'BioBank MQTT 1883' -Direction Inbound -Protocol TCP -LocalPort 1883 -Profile Any -RemoteAddress LocalSubnet -Action Allow | Out-Null
}

Restart-Service mosquitto
Start-Sleep 2
$testArgs = @('-h', '127.0.0.1', '-t', 'biobank/selftest', '-m', 'ok')
if ($useAuth) { $testArgs += @('-u', $User, '-P', $Password) }
& "$MosquittoDir\mosquitto_pub.exe" @testArgs
if ($LASTEXITCODE -eq 0) {
    $mode = if ($useAuth) { "بباسورد (اليوزر: $User)" } else { 'من غير باسورد' }
    Write-Host "Mosquitto شغال $mode، ومفتوح لشبكة المعمل على البورت 1883." -ForegroundColor Green
}
else { Write-Host "Mosquitto مش بيرد. شوفي $logDir\mosquitto.log" -ForegroundColor Red }
